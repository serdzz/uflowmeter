pub fn lookup(c: char) -> Option<[u8; 8]> {
    FONT.iter().find_map(|(ch, p)| if *ch == c { Some(*p) } else { None })
}

/// Cyrillic letters that are visually identical to a Latin glyph
/// already in the HD44780 ROM. Substituting them saves CGRAM slots
/// (only 8 available) AND avoids the mixed-shape look (`Pасхо` vs
/// `Расхо`) the user reported.
pub fn latin_lookalike(c: char) -> Option<u8> {
    let b = match c {
        'А' => b'A',
        'В' => b'B',
        'Е' => b'E',
        'К' => b'K',
        'М' => b'M',
        'Н' => b'H',
        'О' => b'O',
        'Р' => b'P',
        'С' => b'C',
        'Т' => b'T',
        'У' => b'Y',
        'Х' => b'X',
        'а' => b'a',
        'е' => b'e',
        'о' => b'o',
        'р' => b'p',
        'с' => b'c',
        'у' => b'y',
        'х' => b'x',
        _ => return None,
    };
    Some(b)
}
