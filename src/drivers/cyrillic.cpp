std::optional<const std::uint8_t*> lookup(char32_t cp)
{
	for (const auto& e : FONT) {
		if (e.codepoint == cp) {
			return &e.pattern[0];
		}
	}
	return std::nullopt;
}

std::optional<std::uint8_t> latin_lookalike(char32_t cp)
{
	switch (cp) {
	case U'А': return std::uint8_t{'A'};
	case U'В': return std::uint8_t{'B'};
	case U'Е': return std::uint8_t{'E'};
	case U'К': return std::uint8_t{'K'};
	case U'М': return std::uint8_t{'M'};
	case U'Н': return std::uint8_t{'H'};
	case U'О': return std::uint8_t{'O'};
	case U'Р': return std::uint8_t{'P'};
	case U'С': return std::uint8_t{'C'};
	case U'Т': return std::uint8_t{'T'};
	case U'У': return std::uint8_t{'Y'};
	case U'Х': return std::uint8_t{'X'};
	case U'а': return std::uint8_t{'a'};
	case U'е': return std::uint8_t{'e'};
	case U'о': return std::uint8_t{'o'};
	case U'р': return std::uint8_t{'p'};
	case U'с': return std::uint8_t{'c'};
	case U'у': return std::uint8_t{'y'};
	case U'х': return std::uint8_t{'x'};
	default:   return std::nullopt;
	}
}

